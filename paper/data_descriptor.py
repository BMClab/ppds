@app.cell
def _(PolyCollection, np):
    def draw_mesh(ax, mesh):
        # Orthographic view of every STL triangle. All projected dimensions are in cm.
        vertices, faces = mesh
        triangles = vertices[faces] * 100
        centres = triangles.mean(axis=1)
        _, vectors = np.linalg.eigh(np.cov(triangles[:, :, :2].reshape(-1, 2).T))
        along = vectors[:, -1]
        position = centres[:, :2] @ along
        z = centres[:, 2]
        if (
            position[z < np.quantile(z, 0.12)].mean()
            < position[z > np.quantile(z, 0.8)].mean()
        ):
            along = -along
        horizontal = np.array([*along, 0])
        side = np.array([-horizontal[1], horizontal[0], 0])
        up = np.array([0, 0, 1])
        # Look up at the plantar surface, with heel at left and toes at right.
        azimuth, elevation = np.deg2rad([-12, -60])
        right = horizontal * np.cos(azimuth) + side * np.sin(azimuth)
        toward = -horizontal * np.sin(azimuth) + side * np.cos(azimuth)
        view = toward * np.cos(elevation) + up * np.sin(elevation)
        top = up * np.cos(elevation) - toward * np.sin(elevation)
        screen = np.stack([triangles @ right, triangles @ top], axis=-1)
        order = (centres @ view).argsort()
        normals = np.cross(
            triangles[:, 1] - triangles[:, 0], triangles[:, 2] - triangles[:, 0]
        )
        normals /= np.maximum(np.linalg.norm(normals, axis=1, keepdims=True), 1e-10)
        normals[normals @ view < 0] *= -1
        light = -0.45 * right + 0.18 * top + 0.87 * view
        shades = np.clip(normals @ light, 0, 1)
        colors = (0.43 + 0.57 * shades[:, None]) * np.array([0.73, 0.81, 0.83])
        ax.add_collection(
            PolyCollection(
                screen[order],
                facecolors=colors[order],
                edgecolors="face",
                linewidths=0.10,
                rasterized=True,
            )
        )
        ax.autoscale()
        ax.set_aspect("equal")
        ax.axis("off")
        xlo = ax.get_xlim()[0]
        ylo, yhi = ax.get_ylim()
        ax.plot([xlo + 1, xlo + 11], [ylo - 2] * 2, c="#252525", lw=2)
        ax.text(xlo + 1, ylo - 1.4, "10 cm", fontsize=7)
        ax.set_ylim(ylo - 3, yhi)

    return (draw_mesh,)


