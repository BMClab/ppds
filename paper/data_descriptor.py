@app.cell
def _(np, pd, release, trials, zipfile):
    def measure_scans():
        # STL coordinates are stored in metres. Weld exactly coincident vertices
        # before counting how many triangles are incident on each undirected edge.
        dtype = np.dtype(
            [("normal", "<f4", (3,)), ("vertices", "<f4", (3, 3)), ("attribute", "<u2")]
        )
        results = []
        expected = {
            f"scans/{s}{side}_foot.stl"
            for s in trials.subject.unique()
            for side in ("l", "r")
        }
        with zipfile.ZipFile(release.resource_location("scans")) as archive:
            if sorted(expected) != sorted(archive.namelist()):
                raise ValueError("Mesh members differ from participant × side.")
            for member in sorted(expected):
                raw = archive.read(member)
                count = int.from_bytes(raw[80:84], "little")
                if count == 0 or len(raw) != 84 + count * dtype.itemsize:
                    raise ValueError(f"Invalid binary STL triangle count in {member}")
                coords = np.frombuffer(raw, dtype=dtype, offset=84)["vertices"].reshape(
                    -1, 3
                )
                if not np.isfinite(coords).all():
                    raise ValueError(f"Non-finite coordinates in {member}")
                extent = np.ptp(coords, axis=0)
                if np.any(extent <= 0):
                    raise ValueError(f"Zero spatial extent in {member}")
                vertices, inverse = np.unique(coords, axis=0, return_inverse=True)
                faces = inverse.reshape(-1, 3)
                edges = np.sort(
                    np.concatenate(
                        [faces[:, [0, 1]], faces[:, [1, 2]], faces[:, [2, 0]]]
                    ),
                    axis=1,
                )
                _, incidence = np.unique(
                    edges[:, 0] * len(vertices) + edges[:, 1], return_counts=True
                )
                results.append(
                    (
                        member,
                        count,
                        coords[:, 2].min(),
                        *extent,
                        np.sum(incidence == 1),
                        np.sum(incidence > 2),
                    )
                )
        return pd.DataFrame(
            results,
            columns=[
                "Member",
                "Triangles",
                "min_z_m",
                "span_x_m",
                "span_y_m",
                "span_z_m",
                "Boundary edges",
                "Edges with >2 triangles",
            ],
        )

    mesh_metrics = measure_scans()
    return (mesh_metrics,)


