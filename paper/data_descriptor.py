@app.cell
def _(release):
    with release.connect(("trials", "pressure_features")) as _con:
        force_by_activity = _con.sql("""
            SELECT subject,
                   CASE WHEN condition = 'ss' THEN 'Quiet standing'
                        WHEN condition IN ('ws', 'wc', 'wf') THEN 'Walking'
                        WHEN condition = 'rc' THEN 'Running' END AS activity,
                   Mass AS mass_kg, count(DISTINCT trial_id) AS trials,
                   count(*) AS frames, avg(grf_z) AS mean_force_N,
                   max(grf_z) AS peak_force_N
            FROM pressure_features JOIN trials USING (trial_id)
            GROUP BY subject, activity, Mass ORDER BY subject, activity
        """).df()
    standard_gravity = 9.80665  # m/s²
    force_by_activity["body_weight_N"] = force_by_activity.mass_kg * standard_gravity
    force_by_activity["ratio"] = (
        force_by_activity.mean_force_N / force_by_activity.body_weight_N
    )
    force_by_activity["peak_ratio"] = (
        force_by_activity.peak_force_N / force_by_activity.body_weight_N
    )
    standing = (
        force_by_activity.loc[force_by_activity.activity.eq("Quiet standing")]
        .drop(columns=["activity", "trials", "peak_force_N", "peak_ratio"])
        .reset_index(drop=True)
    )
    ratio_quantiles = standing.ratio.quantile(
        [0, 0.25, 0.5, 0.75, 1], interpolation="linear"
    )
    within_ten_percent = int(standing.ratio.between(0.9, 1.1).sum())
    return (
        force_by_activity,
        ratio_quantiles,
        standard_gravity,
        standing,
        within_ten_percent,
    )


