@app.cell
def _(np, pressure_cmap, pressure_norm):
    def draw_pressure_surface(ax, pressure, dx, dy):
        """Join adjacent sensor centres, keeping their original pressures as vertex heights."""
        rows, columns = np.indices(pressure.shape)
        width = pressure.shape[1]
        corner = (rows[:-1, :-1] * width + columns[:-1, :-1]).ravel()
        opposite = corner + width + 1
        triangles = np.vstack(
            [
                np.column_stack((corner, corner + 1, opposite)),
                np.column_stack((corner, opposite, opposite - 1)),
            ]
        )
        heights = pressure.ravel()
        # Keep the transition to zero at each footprint edge and omit the empty floor.
        triangles = triangles[np.any(heights[triangles] > 0, axis=1)]
        ax.plot_trisurf(
            columns.ravel() * dx,
            rows.ravel() * dy,
            heights,
            triangles=triangles,
            cmap=pressure_cmap,
            norm=pressure_norm,
            linewidth=0,
            antialiased=False,
        )
        w, h = width * dx, pressure.shape[0] * dy
        ax.set_proj_type("ortho")
        ax.set(
            xlim=(-dx / 2, w - dx / 2),
            ylim=(-dy / 2, h - dy / 2),
            zlim=(0, pressure_norm.vmax),
        )
        ax.set_box_aspect((w, h, 19), zoom=1.15)
        ax.view_init(elev=35, azim=-54)
        ax.set_axis_off()
        for x in np.arange(0, w, 5):
            ax.plot([x, x], [0, h], [0, 0], color="#c3c3c3", lw=0.4, zorder=0)
        for y in np.arange(0, h, 5):
            ax.plot([0, w], [y, y], [0, 0], color="#c3c3c3", lw=0.4, zorder=0)

    return (draw_pressure_surface,)


