@app.cell
def _(contacts, dataset, example_condition, example_subject, np, trials):
    _trials = trials.loc[
        trials.subject.eq(example_subject) & trials.condition.eq(example_condition)
    ].sort_values("trial")
    _features = dataset.pressure_features(example_subject, example_condition)
    force_passes = {}
    gait_percent = np.arange(101)
    stride_forces = {"R": [], "L": []}
    toe_off_percent = {"R": [], "L": []}
    _offset = 0.0
    for _trial in _trials.itertuples():
        _trace = _features.loc[_features.trial_id.eq(_trial.trial_id)].sort_values(
            "frame"
        )
        _frames = _trace.frame.to_numpy()
        assert np.array_equal(_frames, np.arange(_trial.n_frames))
        _force = {"R": _trace.grf_z_right.to_numpy(), "L": _trace.grf_z_left.to_numpy()}
        force_passes[_trial.trial] = (_offset + _frames / _trial.frequency_hz, _force)
        _offset += _trial.n_frames / _trial.frequency_hz

        # A full stride has two successive onsets of the same foot in one pass,
        # with a contralateral onset between them. Keep measured swing and the next onset.
        _events = list(
            contacts.loc[contacts.trial_id.eq(_trial.trial_id)]
            .sort_values("start_frame")
            .itertuples()
        )
        for _start, _other, _next in zip(_events[:-2], _events[1:-1], _events[2:]):
            _side = _start.side
            if _other.side == _side or _next.side != _side:
                continue
            _lo, _hi = _start.start_frame, _next.start_frame
            _phase = 100 * np.arange(_hi - _lo + 1) / (_hi - _lo)
            stride_forces[_side].append(
                np.interp(gait_percent, _phase, _force[_side][_lo : _hi + 1])
            )
