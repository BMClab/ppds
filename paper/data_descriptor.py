@app.cell
def _(conditions, contacts, mo, pd, people, release, trials, walking):
    with release.connect(("footprints",)) as _con:
        _registered = (
            _con.sql("""
            SELECT condition, count(DISTINCT (trial_id, contact)) AS images
            FROM footprints GROUP BY condition
        """)
            .df()
            .set_index("condition")
            .images
        )
    _trials = trials.groupby("condition").agg(
        Participants=("subject", "nunique"),
        Trials=("trial_id", "size"),
        Frames=("n_frames", "sum"),
    )
    _sides = (
        contacts.groupby(["condition", "side"])
        .size()
        .unstack()
        .rename(columns={"L": "Left contacts", "R": "Right contacts"})
    )
    coverage = (
        _trials.join(_sides)
        .join(_registered.rename("Registered footprints"))
        .loc[list(conditions)]
        .astype("Int64")
    )
    coverage.loc["all"] = coverage.sum()
    coverage.loc["all", "Participants"] = len(people)
    _table = coverage.rename(
        index={**{k: f"{v} ({k})" for k, v in conditions.items()}, "all": "All tasks"}
    )
    _observed = trials.groupby(["subject", "condition"]).size().unstack(fill_value=0)
    planned_passes = 10  # study protocol
    _planned = planned_passes * len(walking) * len(people)
    walk_gaps = (
        _observed[walking]
        .stack()
        .rename("Passes")
        .loc[lambda s: s < planned_passes]
        .reset_index()
    )
    _rc = _observed.loc[_observed.rc.gt(0), "rc"]
    mo.vstack(
        [
            mo.md(f"""
        ## Table 1. Coverage of pressure recordings and derived contacts by task

        All {(_observed[walking] > 0).all(axis=1).sum()} participants contributed every walking speed.
        The deposit contains **{coverage.loc[walking, "Trials"].sum():,} of {_planned:,}** planned walking passes.
        Each of the {len(_rc)} running volunteers completed {_rc.unique().item()} passes.
        Participant totals count distinct people. A dash marks a product outside the scope of a task.
        """),
            mo.ui.table(
                _table.astype(object)
                .fillna("—")
                .rename_axis("Task (code)")
                .reset_index(),
                selection=None,
            ),
            mo.md("**Walking conditions with fewer than ten passes**"),
            mo.ui.table(walk_gaps, selection=None),
        ]
    )
    return coverage, walk_gaps


