@app.cell
def _(
    Path,
    REFERENCE,
    Release,
    ds,
    hashlib,
    local_data_dir,
    metadata_sha256,
    os,
    shutil,
    tempfile,
    urlopen,
    zenodo_record,
):
    # Verify the dictionary itself as well as the eight files it describes.
    def digest(path):
        with path.open("rb") as stream:
            return hashlib.file_digest(stream, "sha256").hexdigest()

    def fetch_verified(name, expected, directory):
        target = directory / name
        if target.exists() and digest(target) == expected:
            return
        with tempfile.NamedTemporaryFile(dir=directory, delete=False) as stream:
            partial = Path(stream.name)
        try:
            with (
                partial.open("wb") as stream,
                urlopen(
                    f"https://zenodo.org/api/records/{zenodo_record}/files/{name}/content",
                    timeout=120,
                ) as response,
            ):
                shutil.copyfileobj(response, stream)
            if digest(partial) != expected:
                raise ValueError(f"Download checksum mismatch for {name}")
            # NamedTemporaryFile creates owner-only files; give the cache normal permissions.
            partial.chmod(0o644)
            partial.replace(target)
        finally:
            partial.unlink(missing_ok=True)

    _local = local_data_dir()
    if os.environ.get("PPDS_DATA", "").strip() or (_local / "metadata.json").is_file():
        data_dir = _local
    else:
        data_dir = (
            Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache")
            / "ppds"
            / str(zenodo_record)
        )
        data_dir.mkdir(parents=True, exist_ok=True)
        fetch_verified("metadata.json", metadata_sha256, data_dir)
        for _spec in REFERENCE["resources"].values():
            fetch_verified(_spec["zenodo_filename"], _spec["sha256"], data_dir)

    release = Release.local(data_dir)
    if (
        digest(data_dir / "metadata.json") != metadata_sha256
        or release.metadata != REFERENCE
    ):
        raise ValueError(
            f"Select the complete PPDS 1.1.1 release from Zenodo record {zenodo_record}."
        )
    for _key, _spec in release.metadata["resources"].items():
        _file = Path(release.resource_location(_key))
        if digest(_file) != _spec["sha256"]:
            raise ValueError(f"File checksum mismatch for {_file.name}")
    ds.use_local(data_dir)
    # Make the configured reader an explicit dependency of downstream cells.
    dataset = ds
    return dataset, release


